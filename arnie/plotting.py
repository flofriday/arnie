def pdf_to_png(pdf_path: Path) -> list[Path]:
    """Try installed rasterizers in order and publish only fresh output pages."""
    pdf_path = pdf_path.resolve()
    with tempfile.TemporaryDirectory(dir=pdf_path.parent) as tmp:
        prefix = Path(tmp) / pdf_path.stem
        commands = [
            [
                gs,
                "-dNOPAUSE",
                "-dBATCH",
                "-sDEVICE=pngalpha",
                "-r150",
                f"-sOutputFile={prefix}-%d.png",
                str(pdf_path),
            ]
            for gs in ("gs", "gswin64c")
        ] + [["pdftoppm", "-r", "150", "-png", str(pdf_path), str(prefix)]]
        for command in commands:
            if not shutil.which(command[0]):
                continue
            for page in Path(tmp).glob("*.png"):
                page.unlink()
            result = subprocess.run(command, capture_output=True, check=False)
            pages = sorted(
                Path(tmp).glob(f"{pdf_path.stem}-*.png"),
                key=lambda p: int(p.stem.rsplit("-", 1)[1]),
            )
            if result.returncode == 0 and pages:
                for old in pdf_path.parent.glob(f"{pdf_path.stem}-*.png"):
                    if old.stem.rsplit("-", 1)[1].isdigit():
                        old.unlink()
                output = []
                for page in pages:
                    destination = pdf_path.parent / page.name
                    shutil.move(page, destination)
                    output.append(destination)
                return output
    print(
        f"Warning: could not convert {pdf_path.name} to PNG "
        "(install Ghostscript or Poppler and check the PDF).",
        file=sys.stderr,
    )
    return []


def cmd_plot(args: argparse.Namespace) -> None:
    data_dir = Path(args.data).resolve()
    if not data_dir.is_dir():
        raise ArnieError(f"Data directory not found: {data_dir}")
    print(f"Loading data from {data_dir}")
    meta, data = load_benchmark(data_dir)
    if not data:
        raise ArnieError("No benchmark data found.")

    plots_dir = Path("plots")
    plots_dir.mkdir(exist_ok=True)

    preamble = gen_preamble_tex(meta, plots_dir)
    print(f"  Generated: {preamble.name}")

    spec_stats = load_spec_stats(data_dir)
    table: Path | None = None
    if spec_stats:
        table = gen_spec_stats_table_tex(spec_stats, plots_dir)
        print(f"  Generated: {table.name}")

    snippets = (
        [gen_total_time_tex(data, plots_dir)]
        + gen_relative_comparison_tex(data, plots_dir, meta.get("builds"))
        + gen_phase_breakdown_tex(data, plots_dir)
        + [gen_phase_breakdown_combined_tex(data, plots_dir)]
    )
    warmup_plot = gen_warmup_plot_tex(data_dir, meta, plots_dir)
    if warmup_plot:
        snippets.append(warmup_plot)
    if spec_stats:
        defs_plot = gen_definitions_vs_time_tex(data, spec_stats, plots_dir)
        if defs_plot:
            snippets.append(defs_plot)
    for s in snippets:
        print(f"  Generated: {s.name}")

    total_time_table = gen_total_time_table_tex(data, plots_dir)
    print(f"  Generated: {total_time_table.name}")

    appendix_tables = [total_time_table]
    speedup_table = gen_speedup_table_tex(data, plots_dir)
    if speedup_table:
        print(f"  Generated: {speedup_table.name}")
        appendix_tables.append(speedup_table)
    if spec_stats:
        fit_table = gen_definitions_vs_time_fit_table_tex(data, spec_stats, plots_dir)
        if fit_table:
            print(f"  Generated: {fit_table.name}")
            appendix_tables.append(fit_table)
    original_family_builds = [
        b
        for b in data
        if BUILD_CONFIGS.get(split_variant(b)[0], {}).get("family") == "original"
    ]
    if original_family_builds:
        pass_rename_table = gen_pass_rename_table_tex(plots_dir)
        print(f"  Generated: {pass_rename_table.name}")
        appendix_tables.append(pass_rename_table)

    plots_tex = gen_plots_tex(preamble, snippets, plots_dir, table, appendix_tables)
    print(f"\n  Compiling {plots_tex.name} ...")
    pdf = compile_tex(plots_tex)
    print(f"  Written:   {pdf}")

    if args.png:
        pngs = pdf_to_png(pdf)
        for png in pngs:
            print(f"  Written:   {png}")

    print(f"\nDone. Plots in {plots_dir.resolve()}")
