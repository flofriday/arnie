def gen_preamble_tex(meta: dict, plots_dir: Path) -> Path:
    system = meta.get("system", {})
    machine = (
        ", ".join(dict.fromkeys(str(v) for v in system.values() if v))
        or "an unspecified system"
    )
    tex = _arnie_header() + f"Benchmarks were recorded on {_tex_escape(machine)}.\n"
    for build in meta.get("builds", meta.get("configurations", [])):
        cfg = BUILD_CONFIGS.get(build, {})
        details = meta.get("build_details", {}).get(build, {})
        commit = details.get(
            "commit", meta.get("commits", {}).get(cfg.get("repo_key"), "unknown")
        )
        runs = details.get("runs", meta.get("runs", "?"))
        warmup = details.get("warmup", meta.get("warmup", "?"))
        tex += (
            f"Configuration \\texttt{{{_tex_escape(build)}}} at commit "
            f"\\texttt{{{_tex_escape(commit[:12])}}} used {_tex_escape(runs)}~timed runs "
            f"after {_tex_escape(warmup)}~warmup runs per specification.\n"
        )
        if source := details.get("source_run"):
            tex += f"Its measurements were reused from \\texttt{{{_tex_escape(source)}}}.\n"
            if source_system := details.get("system"):
                tex += f"Those measurements were recorded on {_tex_escape(', '.join(source_system.values()))}.\n"
    out = plots_dir / "preamble.tex"
    out.write_text(tex)
    return out


def compile_tex(tex_path: Path) -> Path:
    result = subprocess.run(
        ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", tex_path.name],
        check=False,
        cwd=tex_path.parent,
        capture_output=True,
        text=True,
    )
    pdf_path = tex_path.with_suffix(".pdf")
    if result.returncode != 0 or not pdf_path.exists():
        log = tex_path.with_suffix(".log")
        detail = (
            log.read_text(errors="replace")[-3000:] if log.exists() else result.stdout
        )
        raise ArnieError(f"pdflatex error for {tex_path.name}:\n{detail}")
    return pdf_path


def gen_total_time_tex(data: BenchmarkData, plots_dir: Path) -> Path:
    builds = ordered_builds(data)
    specs = benchmark_specs(data)

    means: dict[str, list[float]] = {}
    errs: dict[str, list[float]] = {}
    for build in builds:
        totals_per_spec = [
            [allowed_total(r) for r in data[build].get(spec, [])] for spec in specs
        ]
        means[build] = [statistics.mean(t) if t else 0 for t in totals_per_spec]
        errs[build] = [
            statistics.stdev(t) if len(t) > 1 else 0 for t in totals_per_spec
        ]

    # Builds that actually have data for each spec, in build order.
    present_builds = [[b for b in builds if data[b].get(spec)] for spec in specs]

    # Lay the bars out consecutively (in x-axis data units) instead of pinning
    # each group's center to an integer: bars within a group are STEP apart and
    # the first bar of the next group is GROUP_GAP further on. This keeps the
    # gap between groups even regardless of how many bars each group has. Each
    # spec's tick is then placed at the actual center of its (variable-width)
    # group, so the labels still line up under their bars.
    STEP = 1.0  # center-to-center spacing of bars within a group
    GROUP_GAP = 1.8  # center-to-center spacing across a group boundary
    BAR_FRAC = 0.8  # bar width as a fraction of STEP (leaves a within-group gap)
    EDGE_PAD = 1.2  # blank space (in units) on each side, see enlarge x limits

    bar_x: dict[tuple[str, str], float] = {}
    tick_pos: list[float] = []
    cursor = 0.0
    for j, spec in enumerate(specs):
        present = present_builds[j]
        k = max(1, len(present))
        for idx, build in enumerate(present):
            bar_x[(build, spec)] = cursor + idx * STEP
        tick_pos.append(cursor + (k - 1) * STEP / 2)
        cursor += (k - 1) * STEP + GROUP_GAP

    # Rendered width = bar span + the EDGE_PAD padding added on each side.
    total_units = (cursor - GROUP_GAP) + 2 * EDGE_PAD
    x_unit_cm = 14.0 / total_units  # keep overall width ~14cm (old fixed width)
    bar_width_cm = BAR_FRAC * STEP * x_unit_cm

    addplots = []
    for i, build in enumerate(builds):
        coords = []
        for spec in specs:
            x = bar_x.get((build, spec))
            if x is None:
                continue
            j = specs.index(spec)
            coords.append(
                f"({x:.3f},{means[build][j]:.2f}) +- (0,{errs[build][j]:.2f})"
            )
        if not coords:
            continue
        addplots.append(
            f"\\addplot[{_pgf_style(i)}]\n"
            f"    plot[error bars/.cd, y dir=both, y explicit]\n"
            f"    coordinates {{{' '.join(coords)}}};\n"
            f"\\addlegendentry{{{_tex_escape(build)}}}"
        )

    xtick = ",".join(f"{t:.3f}" for t in tick_pos)
    xticklabels = ",".join(f"{{{_tex_escape(_spec_label(spec))}}}" for spec in specs)
    body = "\n".join(addplots)
    tex = (
        _arnie_header()
        + "\\begin{figure}[H]\n"
        + "\\centering\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tikzpicture}\n"
        + "\\begin{axis}[\n"
        + "    ybar,\n"
        + "    bar shift=0pt,\n"
        + f"    bar width={bar_width_cm:.3f}cm,\n"
        + f"    x={x_unit_cm}cm, height=8cm,\n"
        + f"    xtick={{{xtick}}},\n"
        + f"    xticklabels={{{xticklabels}}},\n"
        + "    xticklabel style={anchor=north,font=\\small},\n"
        + f"    enlarge x limits={{abs={EDGE_PAD}}},\n"
        + "    xlabel={Specification},\n"
        + "    ylabel={Parsing time},\n"
        + "    legend style={at={(1.02,1)},anchor=north west,nodes={anchor=west},font=\\small},\n"
        + _AXIS_BASE
        + "    ymode=log, log basis y=10,\n"
        # Fixed floor, not derived from the data, so sub-millisecond bars stay
        # visible and the axis looks the same across runs.
        + "    ymin=0.1,\n"
        + "    ytick={0.1,0.5,1,5,10,50,100,500,1000,5000},\n"
        + "    yticklabels={0.1ms,0.5ms,1ms,5ms,10ms,50ms,100ms,500ms,1s,5s},\n"
        + "    yticklabel style={font=\\small},\n"
        + "    log origin=infty,\n"
        + "]\n"
        + body
        + "\n"
        + "\\end{axis}\n"
        + "\\end{tikzpicture}%\n"
        + "}\n"
        + "\\caption{Parsing time per specification (logarithmic scale, lower is better).}\n"
        + "\\label{fig:total_time}\n"
        + "\\end{figure}\n"
    )
    out = plots_dir / "total_time.tex"
    out.write_text(tex)
    return out


def gen_total_time_table_tex(data: BenchmarkData, plots_dir: Path) -> Path:
    builds = ordered_builds(data)
    specs = benchmark_specs(data)

    col_spec = "|l|" + "r|" * len(builds)
    header = " & ".join(
        ["\\textbf{Specification}"]
        + [f"\\textbf{{{_tex_escape(b)}}} (ms)" for b in builds]
    )

    rows = []
    for spec in specs:
        cells = []
        for build in builds:
            totals = [allowed_total(r) for r in data[build].get(spec, [])]
            if totals:
                mean = statistics.mean(totals)
                std = statistics.stdev(totals) if len(totals) > 1 else 0.0
                cells.append(f"{mean:.1f} $\\pm$ {std:.1f}")
            else:
                cells.append("---")
        rows.append(f"    {_tex_escape(spec)} & {' & '.join(cells)} \\\\")

    tex = (
        _arnie_header()
        + "\\begin{table}[H]\n"
        + "\\centering\n"
        + "\\begin{tabular}{"
        + col_spec
        + "}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\caption{Parseing time per specification and configuration (mean $\\pm$ stddev, in milliseconds, lower is better).}\n"
        "\\label{tab:total_time}\n"
        "\\end{table}\n"
    )
    out = plots_dir / "total_time_table.tex"
    out.write_text(tex)
    return out


def _phase_means(
    phases: list[str], build_data: dict[str, list[dict[str, float]]], specs: list[str]
) -> dict[str, dict[str, float]]:
    """Return means[spec][phase] normalized so each spec's phases sum to 1."""
    raw: dict[str, dict[str, float]] = {
        spec: {
            phase: statistics.mean(
                [r.get(phase, 0.0) for r in build_data.get(spec, [])] or [0]
            )
            for phase in phases
        }
        for spec in specs
    }
    for spec in specs:
        total = sum(raw[spec].values()) or 1.0
        for phase in phases:
            raw[spec][phase] /= total
    return raw


def _stacked_addplots(
    phases: list[str],
    build_data: dict[str, list[dict[str, float]]],
    specs: list[str],
    first: bool,
) -> str:
    means = _phase_means(phases, build_data, specs)
    lines = []
    for i, phase in enumerate(phases):
        coords = " ".join(f"({spec},{means[spec][phase]:.4f})" for spec in specs)
        entry = f"\\addlegendentry{{{_tex_escape(phase)}}}" if first else ""
        lines.append(f"\\addplot[{_pgf_style(i)}] coordinates {{{coords}}};\n{entry}")
    return "\n".join(lines)


