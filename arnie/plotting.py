def _linfit(points: list[tuple[float, float]]) -> tuple[float, float] | None:
    """Ordinary least-squares fit y = m*x + d. None if it can't be determined."""
    n = len(points)
    if n < 2:
        return None
    mean_x = sum(x for x, _ in points) / n
    mean_y = sum(y for _, y in points) / n
    sxx = sum((x - mean_x) ** 2 for x, _ in points)
    if sxx == 0:  # all x equal -> no slope
        return None
    sxy = sum((x - mean_x) * (y - mean_y) for x, y in points)
    m = sxy / sxx
    d = mean_y - m * mean_x
    return m, d


def _definitions_vs_time_points(
    data: BenchmarkData, spec_stats: SpecStats
) -> dict[str, list[tuple[float, float]]]:
    """Per configuration (total node size, mean compile time) points, in configuration order."""
    specs = ordered_specs(spec_stats)
    node_sizes = {
        s: (
            spec_stats[s]["Total Definitions"]
            + spec_stats[s]["Total Statements"]
            + spec_stats[s]["Total Expressions"]
        )
        for s in specs
        if all(
            k in spec_stats[s]
            for k in (
                "Total Definitions",
                "Total Statements",
                "Total Expressions",
            )
        )
    }
    points: dict[str, list[tuple[float, float]]] = {}
    for build in ordered_builds(data):
        pts = []
        for spec in specs:
            if spec not in node_sizes:
                continue
            runs = data[build].get(spec, [])
            if not runs:
                continue
            mean_time = statistics.mean([allowed_total(r) for r in runs])
            pts.append((float(node_sizes[spec]), mean_time))
        if pts:
            points[build] = pts
    return points


def gen_definitions_vs_time_tex(
    data: BenchmarkData, spec_stats: SpecStats, plots_dir: Path
) -> Path | None:
    builds = ordered_builds(data)
    points = _definitions_vs_time_points(data, spec_stats)
    if not points:
        return None

    # Lines are drawn first so the markers sit on top of them.
    line_plots = []
    marker_plots = []
    for i, build in enumerate(builds):
        pts = points.get(build)
        if not pts:
            continue
        color, mark = _LINE_STYLES[i % len(_LINE_STYLES)]
        coords = " ".join(f"({x:.0f},{y:.2f})" for x, y in pts)
        marker_plots.append(
            f"\\addplot[only marks, color={color}, mark={mark}, mark size=3pt] "
            f"coordinates {{{coords}}};\n"
            f"\\addlegendentry{{{_label(build)}}}"
        )
        fit = _linfit(pts)
        if fit:
            m, d = fit
            x0 = min(x for x, _ in pts)
            x1 = max(x for x, _ in pts)
            line_plots.append(
                f"\\addplot[color={color}, dashed, line width=1pt, forget plot] "
                f"coordinates {{({x0:.0f},{m * x0 + d:.2f}) "
                f"({x1:.0f},{m * x1 + d:.2f})}};"
            )

    body = "\n".join(line_plots + marker_plots)
    tex = (
        _arnie_header()
        + "\\begin{figure}[ht]\n"
        + "\\centering\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tikzpicture}\n"
        + "\\begin{axis}[\n"
        + "    width=12cm, height=7cm,\n"
        + "    xlabel={Total node size},\n"
        + "    ylabel={Total compile time (ms)},\n"
        + "    legend style={at={(1.02,1)},anchor=north west,nodes={anchor=west},font=\\small},\n"
        + _AXIS_BASE
        + "]\n"
        + body
        + "\n"
        + "\\end{axis}\n"
        + "\\end{tikzpicture}%\n"
        + "}\n"
        + "\\caption{Compile time as a function of specification size (total definitions, statements, and expressions).}\n"
        + "\\label{fig:definitions_vs_time}\n"
        + "\\end{figure}\n"
    )
    out = plots_dir / "definitions_vs_time.tex"
    out.write_text(tex)
    return out


def gen_definitions_vs_time_fit_table_tex(
    data: BenchmarkData, spec_stats: SpecStats, plots_dir: Path
) -> Path | None:
    points = _definitions_vs_time_points(data, spec_stats)

    rows = []
    for build in ordered_builds(data):
        fit = _linfit(points.get(build, []))
        if not fit:
            continue
        m, d = fit
        scaled_m = m * 1000
        sign = "+" if d >= 0 else "-"
        slope = f"${scaled_m:.2f}\\cdot 10^{{-3}}$"
        eq = f"$y = {scaled_m:.2f}\\cdot 10^{{-3}}\\,x {sign} {abs(d):.2f}$"
        rows.append(f"    {_label(build)} & {slope} & {d:.2f} & {eq} \\\\")
    if not rows:
        return None

    header = " & ".join(
        [
            "\\textbf{Configuration}",
            "\\textbf{Slope $m$ (ms/node)}",
            "\\textbf{Intercept $d$ (ms)}",
            "\\textbf{Fit $y = mx + d$}",
        ]
    )
    tex = (
        _arnie_header()
        + "\\begin{table}[htbp]\n"
        + "\\centering\n"
        + "\\begin{tabular}{|l|r|r|l|}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\caption{Least-squares linear fit of compile time vs.\\ total "
        "node size.}\n"
        "\\label{tab:definitions_vs_time_fit}\n"
        "\\end{table}\n"
    )
    out = plots_dir / "definitions_vs_time_fit.tex"
    out.write_text(tex)
    return out


def gen_spec_stats_table_tex(spec_stats: SpecStats, plots_dir: Path) -> Path:
    specs = ordered_specs(spec_stats)

    def header_cell(s: str) -> str:
        parts = s.split("-")
        text = "-\\\\\n".join([f"\\textbf{{{_tex_escape(p)}}}" for p in parts])
        return f"\\makecell[r]{{{text}}}"

    col_spec = "|l" + "|r" * len(specs) + "|"
    header = " & ".join(["\\textbf{Metric}"] + [header_cell(s) for s in specs])

    all_stats = list(
        dict.fromkeys(stat for stats in spec_stats.values() for stat in stats)
    )
    rows = []
    for stat in all_stats:
        vals = []
        for s in specs:
            v = spec_stats[s].get(stat)
            vals.append(f"\\num{{{v}}}" if v is not None else "---")
        rows.append(f"    {_tex_escape(stat)} & {' & '.join(vals)} \\\\")

    # Rotated 90deg (sidewaystable) so the wide table uses the page's long
    # dimension; this keeps it readable at \footnotesize instead of \tiny.
    tex = (
        _arnie_header()
        + "\\begin{sidewaystable}\n"
        + "\\centering\n"
        + "\\footnotesize\n"
        + "\\begin{tabular}{"
        + col_spec
        + "}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\caption{Statistics for each benchmarked specification.}\n"
        "\\label{tab:spec_stats}\n"
        "\\end{sidewaystable}\n"
    )
    out = plots_dir / "spec_stats.tex"
    out.write_text(tex)
    return out


def _speedup_pairs(data: BenchmarkData) -> list[tuple[str, str]]:
    """Return (baseline, compared) pairs for the speedup table.

    Fixed pairs cover known build combinations. Variant pairs compare
    consecutive refs of the same base build (e.g. graalvm@main vs
    graalvm@feature).
    """
    builds = ordered_builds(data)
    pairs = [
        (a, b)
        for a, b in [
            ("original", "graalvm"),
            ("original", "native"),
            ("graalvm", "native"),
        ]
        if a in data and b in data
    ]
    by_base: dict[str, list[str]] = {}
    for build in builds:
        base, ref = split_variant(build)
        if ref:
            by_base.setdefault(base, []).append(build)
    for variants in by_base.values():
        for i in range(len(variants) - 1):
            pairs.append((variants[i], variants[i + 1]))
    return pairs


def gen_speedup_table_tex(data: BenchmarkData, plots_dir: Path) -> Path | None:
    specs = benchmark_specs(data)
    pairs = _speedup_pairs(data)
    if not pairs:
        return None

    col_spec = "|l" + "|r" * len(pairs) + "|"
    header = " & ".join(
        ["\\textbf{Specification}"]
        + [f"\\textbf{{{_label(b)} vs {_label(a)}}}" for a, b in pairs]
    )

    rows = []
    for spec in specs:
        cells = []
        for a, b in pairs:
            a_runs = data[a].get(spec, [])
            b_runs = data[b].get(spec, [])
            if a_runs and b_runs:
                a_mean = statistics.mean([allowed_total(r) for r in a_runs])
                b_mean = statistics.mean([allowed_total(r) for r in b_runs])
                cells.append(f"{a_mean / b_mean:.2f}$\\times$" if b_mean > 0 else "---")
            else:
                cells.append("---")
        if all(c == "---" for c in cells):
            continue
        rows.append(f"    {_tex_escape(spec)} & {' & '.join(cells)} \\\\")

    if not rows:
        return None

    tex = (
        _arnie_header()
        + "\\begin{table}[htbp]\n"
        + "\\centering\n"
        + "\\begin{tabular}{"
        + col_spec
        + "}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        + "\\caption{Speedup of one configuration over another (higher is better).}\n"
        + "\\label{tab:speedup}\n"
        + "\\end{table}\n"
    )
    out = plots_dir / "speedup.tex"
    out.write_text(tex)
    return out


