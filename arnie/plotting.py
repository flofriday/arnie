def _arnie_header() -> str:
    ts = datetime.now(UTC).strftime("%Y-%m-%d %H:%M")
    return f"% Automatically generated by arnie.py at {ts}\n"


def _tex_escape(value: object) -> str:
    replacements = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(c, c) for c in str(value))


