def gen_plots_tex(
    preamble: Path,
    snippet_paths: list[Path],
    plots_dir: Path,
    table: Path | None = None,
    appendix_tables: list[Path] | None = None,
) -> Path:
    figures = "\n".join(f"\\input{{{p.name}}}" for p in snippet_paths)
    table_input = f"\\input{{{table.name}}}\n" if table else ""
