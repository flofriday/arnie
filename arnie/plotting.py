def gen_phase_breakdown_combined_tex(data: BenchmarkData, plots_dir: Path) -> Path:
    builds = ordered_builds(data)
    specs = benchmark_specs(data)
    phases = allowed_phases(data)

    # Normalized means: means[build][spec][phase] sums to 1 per (build, spec)
    norm: dict[str, dict[str, dict[str, float]]] = {
        build: _phase_means(phases, data[build], specs) for build in builds
    }

    # Only place a bar for (spec, build) pairs that actually have data, and pack
    # them with a running cursor so specs missing a build don't reserve an empty,
    # labelled slot. STEP separates bars in a group, GROUP_GAP separates groups.
    STEP = 1.0
    GROUP_GAP = 1.8
    present_builds = {spec: [b for b in builds if data[b].get(spec)] for spec in specs}

    bar_x: dict[tuple[str, str], float] = {}
    centers = []
    cursor = 0.0
    for spec in specs:
        present = present_builds[spec]
        k = max(1, len(present))
        for idx, build in enumerate(present):
            bar_x[(spec, build)] = cursor + idx * STEP
        centers.append(cursor + (k - 1) * STEP / 2)
        cursor += (k - 1) * STEP + GROUP_GAP
    xmax = (cursor - GROUP_GAP) + STEP  # last bar plus a little margin

    # Flat (spec, build) order shared by every stacked series.
    pairs = [(spec, build) for spec in specs for build in present_builds[spec]]

    addplots = []
    for pi, phase in enumerate(phases):
        coords = " ".join(
            f"({bar_x[(spec, build)]:.2f},{norm[build][spec][phase]:.4f})"
            for spec, build in pairs
        )
        addplots.append(
            f"\\addplot[{_pgf_style(pi)}] coordinates {{{coords}}};\n"
            f"\\addlegendentry{{{_tex_escape(phase)}}}"
        )

    xtick = ",".join(f"{c:.2f}" for c in centers)
    xticklabels = ",".join(f"{{{_tex_escape(spec)}}}" for spec in specs)

    # Build names sit on top of each bar (every stack sums to 1, so the top is
    # at y=1); spec names are the bottom x-axis labels.
    build_labels = "\n".join(
        f"\\node[font=\\tiny,rotate=30,anchor=south west,inner sep=2pt] "
        f"at (axis cs:{bar_x[(spec, build)]:.2f},1) {{{_tex_escape(build)}}};"
        for spec, build in pairs
    )

    body = "\n".join(addplots) + "\n" + build_labels
    tex = (
        _arnie_header()
        + "\\begin{figure}[htbp]\n"
        + "\\centering\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tikzpicture}\n"
        + "\\begin{axis}[\n"
        + "    ybar stacked,\n"
        + "    bar width=10pt,\n"
        + "    width=15cm, height=8cm,\n"
        + "    clip=false,\n"
        + f"    xmin=-1, xmax={xmax:.1f},\n"
        + f"    xtick={{{xtick}}},\n"
        + f"    xticklabels={{{xticklabels}}},\n"
        + "    xticklabel style={rotate=20,anchor=north east,font=\\small},\n"
        + "    ymin=0, ymax=1,\n"
        + "    xlabel={Specification},\n"
        + "    ylabel={Fraction of compile time},\n"
        + "    legend style={at={(1.02,1)},anchor=north west,font=\\small},\n"
        + _AXIS_BASE
        + "]\n"
        + body
        + "\n"
        + "\\end{axis}\n"
        + "\\end{tikzpicture}%\n"
        + "}\n"
        + "\\caption{Pass breakdown across all specifications and configurations.}\n"
        + "\\label{fig:phase_breakdown}\n"
        + "\\end{figure}\n"
    )
    out = plots_dir / "phase_breakdown.tex"
    out.write_text(tex)
    return out


def gen_warmup_plot_tex(data_dir: Path, meta: dict, plots_dir: Path) -> Path | None:
    spec = "miniARMv7"
    builds = ordered_builds(
        {b: None for b in meta.get("builds", meta.get("configurations", []))}
    )
    series: dict[str, list[float]] = {}
    warmups: dict[str, int] = {}
    for build in builds:
        build_dir = data_dir / build / spec
        if not build_dir.exists():
            continue
        family = BUILD_CONFIGS.get(build, {}).get("family", "openvadl")
        totals = load_all_runs_total(build_dir, family)
        if totals:
            series[build] = totals
            warmups[build] = len(run_files(build_dir, "warmup"))

    if not series:
        return None

    addplots = []
    for i, (build, totals) in enumerate(series.items()):
        color, mark = _LINE_STYLES[i % len(_LINE_STYLES)]
        coords = " ".join(f"({j + 1},{t:.2f})" for j, t in enumerate(totals))
        addplots.append(
            f"\\addplot[color={color}, mark={mark}, line width=1pt] "
            f"coordinates {{{coords}}};\n"
            f"\\addlegendentry{{{_tex_escape(build)}}}"
        )

    separators = []
    same_warmup = len(set(warmups.values())) == 1
    top = max(max(totals) for totals in series.values()) or 1
    for i, count in enumerate(warmups.values()):
        if count:
            color = "gray!60" if same_warmup else _LINE_STYLES[i % len(_LINE_STYLES)][0]
            separators.append(
                f"\\draw[dashed, {color}, thick] (axis cs:{count + 0.5},0) "
                f"-- (axis cs:{count + 0.5},{top:.2f});"
            )
        if same_warmup:
            break
    body = "\n".join(addplots + separators)

    tex = (
        _arnie_header()
        + "\\begin{figure}[htbp]\n"
        + "\\centering\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tikzpicture}\n"
        + "\\begin{axis}[\n"
        + "    width=12cm, height=7cm,\n"
        + "    xlabel={Run},\n"
        + "    ylabel={Compile time (ms)},\n"
        + "    legend style={at={(1.02,1)},anchor=north west,nodes={anchor=west},font=\\small},\n"
        + _AXIS_BASE
        + "]\n"
        + body
        + "\n"
        + "\\end{axis}\n"
        + "\\end{tikzpicture}%\n"
        + "}\n"
        + "\\caption{Parseing time per run for \\texttt{miniARMv7} including warmup. Dashed lines mark the end of warmup; colors match configurations when warmup counts differ (lower is better).}\n"
        + "\\label{fig:warmup_miniARMv7}\n"
        + "\\end{figure}\n"
    )
    out = plots_dir / "warmup_miniARMv7.tex"
    out.write_text(tex)
    return out


def _linfit(points: list[tuple[float, float]]) -> tuple[float, float] | None:
    """Ordinary least-squares fit y = m*x + d. None if it can't be determined."""
    n = len(points)
    if n < 2:
        return None
    mean_x = sum(x for x, _ in points) / n
    mean_y = sum(y for _, y in points) / n
    sxx = sum((x - mean_x) ** 2 for x, _ in points)
    if sxx == 0:  # all x equal -> no slope
        return None
    sxy = sum((x - mean_x) * (y - mean_y) for x, y in points)
    m = sxy / sxx
    d = mean_y - m * mean_x
    return m, d


def _definitions_vs_time_points(
    data: BenchmarkData, spec_stats: SpecStats
) -> dict[str, list[tuple[float, float]]]:
    """Per configuration (total node size, mean compile time) points, in configuration order."""
    specs = ordered_specs(spec_stats)
    node_sizes = {
        s: (
            spec_stats[s]["Total Definitions"]
            + spec_stats[s]["Total Statements"]
            + spec_stats[s]["Total Expressions"]
        )
        for s in specs
        if all(
            k in spec_stats[s]
            for k in (
                "Total Definitions",
                "Total Statements",
                "Total Expressions",
            )
        )
    }
    points: dict[str, list[tuple[float, float]]] = {}
    for build in ordered_builds(data):
        pts = []
        for spec in specs:
            if spec not in node_sizes:
                continue
            runs = data[build].get(spec, [])
            if not runs:
                continue
            mean_time = statistics.mean([allowed_total(r) for r in runs])
            pts.append((float(node_sizes[spec]), mean_time))
        if pts:
            points[build] = pts
    return points


def gen_definitions_vs_time_tex(
    data: BenchmarkData, spec_stats: SpecStats, plots_dir: Path
) -> Path | None:
    builds = ordered_builds(data)
    points = _definitions_vs_time_points(data, spec_stats)
    if not points:
        return None

    # Lines are drawn first so the markers sit on top of them.
    line_plots = []
    marker_plots = []
    for i, build in enumerate(builds):
        pts = points.get(build)
        if not pts:
            continue
        color, mark = _LINE_STYLES[i % len(_LINE_STYLES)]
        coords = " ".join(f"({x:.0f},{y:.2f})" for x, y in pts)
        marker_plots.append(
            f"\\addplot[only marks, color={color}, mark={mark}, mark size=3pt] "
            f"coordinates {{{coords}}};\n"
            f"\\addlegendentry{{{_tex_escape(build)}}}"
        )
        fit = _linfit(pts)
        if fit:
            m, d = fit
            x0 = min(x for x, _ in pts)
            x1 = max(x for x, _ in pts)
            line_plots.append(
                f"\\addplot[color={color}, dashed, line width=1pt, forget plot] "
                f"coordinates {{({x0:.0f},{m * x0 + d:.2f}) "
                f"({x1:.0f},{m * x1 + d:.2f})}};"
            )

    body = "\n".join(line_plots + marker_plots)
    tex = (
        _arnie_header()
        + "\\begin{figure}[ht]\n"
        + "\\centering\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tikzpicture}\n"
        + "\\begin{axis}[\n"
        + "    width=12cm, height=7cm,\n"
        + "    xlabel={Total node size},\n"
        + "    ylabel={Total compile time (ms)},\n"
        + "    legend style={at={(1.02,1)},anchor=north west,nodes={anchor=west},font=\\small},\n"
        + _AXIS_BASE
        + "]\n"
        + body
        + "\n"
        + "\\end{axis}\n"
        + "\\end{tikzpicture}%\n"
        + "}\n"
        + "\\caption{Compile time as a function of specification size (total definitions, statements, and expressions).}\n"
        + "\\label{fig:definitions_vs_time}\n"
        + "\\end{figure}\n"
    )
    out = plots_dir / "definitions_vs_time.tex"
    out.write_text(tex)
    return out


def gen_definitions_vs_time_fit_table_tex(
    data: BenchmarkData, spec_stats: SpecStats, plots_dir: Path
) -> Path | None:
    points = _definitions_vs_time_points(data, spec_stats)

    rows = []
    for build in ordered_builds(data):
        fit = _linfit(points.get(build, []))
        if not fit:
            continue
        m, d = fit
        scaled_m = m * 1000
        sign = "+" if d >= 0 else "-"
        slope = f"${scaled_m:.2f}\\cdot 10^{{-3}}$"
        eq = f"$y = {scaled_m:.2f}\\cdot 10^{{-3}}\\,x {sign} {abs(d):.2f}$"
        rows.append(f"    {_tex_escape(build)} & {slope} & {d:.2f} & {eq} \\\\")
    if not rows:
        return None

    header = " & ".join(
        [
            "\\textbf{Configuration}",
            "\\textbf{Slope $m$ (ms/node)}",
            "\\textbf{Intercept $d$ (ms)}",
            "\\textbf{Fit $y = mx + d$}",
        ]
    )
    tex = (
        _arnie_header()
        + "\\begin{table}[htbp]\n"
        + "\\centering\n"
        + "\\begin{tabular}{|l|r|r|l|}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "\\caption{Least-squares linear fit of compile time vs.\\ total "
        "node size.}\n"
        "\\label{tab:definitions_vs_time_fit}\n"
        "\\end{table}\n"
    )
    out = plots_dir / "definitions_vs_time_fit.tex"
    out.write_text(tex)
    return out


def gen_spec_stats_table_tex(spec_stats: SpecStats, plots_dir: Path) -> Path:
    specs = ordered_specs(spec_stats)

    def header_cell(s: str) -> str:
        s = _spec_label(s)
        parts = s.split("-")
        text = "-\\\\\n".join([f"\\textbf{{{_tex_escape(p)}}}" for p in parts])
        return f"\\makecell[r]{{{text}}}"

    col_spec = "|l" + "|r" * len(specs) + "|"
    header = " & ".join(["\\textbf{Metric}"] + [header_cell(s) for s in specs])

    all_stats = list(
        dict.fromkeys(stat for stats in spec_stats.values() for stat in stats)
    )
    groups = []
    grouped = set()
    model_stats = (
        "Model Definitions",
        "Record Definitions",
        "Model-Type Definitions",
    )
    for stat in all_stats:
        if stat in grouped:
            continue
        base = stat.removesuffix(" Unexpanded").removesuffix(" Expanded")
        original = base + " Unexpanded"
        expanded = base + " Expanded"
        if stat in model_stats:
            group = [metric for metric in model_stats if metric in all_stats]
        elif base in all_stats and expanded in all_stats:
            group = [base, expanded]
        elif original in all_stats and base in all_stats:
            group = [original, base]
        else:
            group = [stat]
        groups.append(group)
        grouped.update(group)

    rows = []
    for group in groups:
        paired = len(group) == 2 and group[0] not in model_stats
        if rows:
            rows.append("\\hline")
        for index, stat in enumerate(group):
            vals = []
            for s in specs:
                v = spec_stats[s].get(stat)
                vals.append(f"\\num{{{v}}}" if v is not None else "---")
            if paired:
                label = stat.removesuffix(" Unexpanded").removesuffix(" Expanded")
                label += " Orig." if index == 0 else " Exp."
            else:
                label = stat.removesuffix(" Unexpanded") + (
                    " Orig." if stat.endswith(" Unexpanded") else ""
                )
            rows.append(f"    {_tex_escape(label)} & {' & '.join(vals)} \\\\")

    # Compact labels and padding keep the portrait table readable; scaling
    # bounds its width when more specifications or larger counts are present.
    tex = (
        _arnie_header()
        + "\\begin{table}[htbp]\n"
        + "\\centering\n"
        + "\\footnotesize\n"
        + "\\setlength{\\tabcolsep}{3pt}\n"
        + "\\resizebox{\\linewidth}{!}{%\n"
        + "\\begin{tabular}{"
        + col_spec
        + "}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        "}\n"
        "\\caption{Statistics for each benchmarked specification.}\n"
        "\\label{tab:spec_stats}\n"
        "\\end{table}\n"
    )
    out = plots_dir / "spec_stats.tex"
    out.write_text(tex)
    return out


def gen_speedup_table_tex(data: BenchmarkData, plots_dir: Path) -> Path | None:
    specs = benchmark_specs(data)
    candidate_pairs = [
        ("original", "graalvm"),
        ("original", "native"),
        ("graalvm", "native"),
    ]
    pairs = [(a, b) for a, b in candidate_pairs if a in data and b in data]
    if not pairs:
        return None

    col_spec = "|l" + "|r" * len(pairs) + "|"
    header = " & ".join(
        ["\\textbf{Specification}"]
        + [f"\\textbf{{{_tex_escape(b)} vs {_tex_escape(a)}}}" for a, b in pairs]
    )

    rows = []
    for spec in specs:
        cells = []
        for a, b in pairs:
            a_runs = data[a].get(spec, [])
            b_runs = data[b].get(spec, [])
            if a_runs and b_runs:
                a_mean = statistics.mean([allowed_total(r) for r in a_runs])
                b_mean = statistics.mean([allowed_total(r) for r in b_runs])
                cells.append(f"{a_mean / b_mean:.2f}$\\times$" if b_mean > 0 else "---")
            else:
                cells.append("---")
        if all(c == "---" for c in cells):
            continue
        rows.append(f"    {_tex_escape(spec)} & {' & '.join(cells)} \\\\")

    if not rows:
        return None

    tex = (
        _arnie_header()
        + "\\begin{table}[htbp]\n"
        + "\\centering\n"
        + "\\begin{tabular}{"
        + col_spec
        + "}\n"
        "\\hline\n"
        f"    {header} \\\\\n"
        "\\hline\n" + "\n".join(rows) + "\n"
        "\\hline\n"
        "\\end{tabular}\n"
        + "\\caption{Speedup of one configuration over another (higher is better).}\n"
        + "\\label{tab:speedup}\n"
        + "\\end{table}\n"
    )
    out = plots_dir / "speedup.tex"
    out.write_text(tex)
    return out


